const glyphs = new Map<string, number[][]>();
for (const [ch, rows] of Object.entries(G)) {
  glyphs.set(ch, rows.split(' ').map((r) => [...r].map(Number)));
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function textWidth(text: string, scale = 1, spacing = 1): number {
  return text.length ? text.length * (GLYPH_W + spacing) * scale - spacing * scale : 0;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  colour: string,
  scale = 1,
  opts: { shadow?: string; spacing?: number; align?: 'left' | 'centre' | 'right' } = {},
): void {
  const spacing = opts.spacing ?? 1;
  const w = textWidth(text, scale, spacing);
  let cx = Math.round(opts.align === 'centre' ? x - w / 2 : opts.align === 'right' ? x - w : x);
  const up = text.toUpperCase();
  const draw = (ox: number, oy: number, col: string) => {
    ctx.fillStyle = col;
    let px = cx + ox;
    for (const ch of up) {
      const g = glyphs.get(ch) ?? glyphs.get('?')!;
      for (let r = 0; r < GLYPH_H; r++) {
        for (let c = 0; c < GLYPH_W; c++) {
          if (g[r][c]) ctx.fillRect(px + c * scale, Math.round(y) + oy + r * scale, scale, scale);
        }
      }
      px += (GLYPH_W + spacing) * scale;
    }
  };
  if (opts.shadow) draw(scale, scale, opts.shadow);
  draw(0, 0, colour);
}

/** Word-wrap text to a maximum pixel width at the given scale. */
export function wrapText(text: string, maxWidth: number, scale = 1): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let line = '';
  for (const w of words) {
    const next = line ? `${line} ${w}` : w;
    if (textWidth(next, scale) > maxWidth && line) {
      lines.push(line);
      line = w;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}
